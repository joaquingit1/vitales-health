"""Bundle the package's configuration documents for the design prototype.

The prototype opens from disk, where a browser cannot fetch JSON files, so this
script copies each configuration document unchanged into config-bundle.js as
window.CREW_CONFIG, keyed by file name, with the SHA-256 of the file as its
version. Run it after editing any of the documents (the kit map included):

    python3 -I design/tools/bundle-config.py

The documents stay the single source of truth; config-bundle.js is a build output.
"""
import hashlib, json, os

HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.dirname(os.path.dirname(HERE))
DOCS = ["environment-hazards.json", "routine-schedule.json", "responder-flows.json"]
# Documents written at the event. Until each exists at the package root, the prototype
# renders the contract's example document (marked example) from api/examples.
EVENT_DOCS = {
    "kit-map.json": os.path.join("api", "examples", "kit-map.example.json"),
    "onboard-plans.json": os.path.join("api", "examples", "config", "onboard-plans.example.json"),
    "skills-catalog.json": os.path.join("api", "examples", "config", "skills-catalog.example.json"),
    "role-rules.json": os.path.join("api", "examples", "config", "role-rules.example.json"),
    "ui-copy.json": os.path.join("api", "examples", "config", "ui-copy.example.json"),
}


def load(path):
    raw = open(path, "rb").read()
    doc = json.loads(raw)
    # OpenAPI example files wrap the document as {summary, description, x-schema, value}
    if isinstance(doc, dict) and "value" in doc and "x-schema" in doc:
        doc = doc["value"]
    return hashlib.sha256(raw).hexdigest(), doc


out = {}
for name in DOCS:
    version, doc = load(os.path.join(PKG, name))
    out[name] = {"version": version, "document": doc}
for name, example in EVENT_DOCS.items():
    rel = name if os.path.exists(os.path.join(PKG, name)) else example
    path = os.path.join(PKG, rel)
    if os.path.exists(path):
        version, doc = load(path)
        out[name] = {"version": version, "source": rel, "document": doc}

body = json.dumps(out, ensure_ascii=False, separators=(",", ":"))
target = os.path.join(PKG, "design", "config-bundle.js")
with open(target, "w", encoding="utf-8") as f:
    f.write("/* Generated by design/tools/bundle-config.py from " + ", ".join(v.get("source", k) for k, v in out.items()) + ". Do not edit by hand. */\n")
    f.write("window.CREW_CONFIG = " + body + ";\n")
print(target, ", ".join(out), len(body), "bytes")
