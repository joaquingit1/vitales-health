"""Application persistence boundary, implemented by the SQLite adapter."""

from typing import Protocol

from crew_health.kernel.uow import ReadSnapshot, UnitOfWork
from crew_health.plans.application.ports import EscalationIntent
from crew_health.plans.domain.run import PlanRun

type View = ReadSnapshot | UnitOfWork


class PlanRunsRepository(Protocol):
    def insert(self, uow: UnitOfWork, run: PlanRun, plan_version: str) -> None: ...
    def save(self, uow: UnitOfWork, run: PlanRun) -> None: ...
    def load(self, view: View, plan_run_id: str) -> PlanRun | None: ...
    def version(self, view: View, plan_run_id: str) -> str | None: ...
    def list_open(
        self, view: View, subject_person_id: str, after: str | None, limit: int
    ) -> tuple[PlanRun, ...]: ...
    def open_for(self, view: View, plan_id: str, subject: str, episode_or_session: str) -> str | None: ...
    def pin_plan(self, uow: UnitOfWork, version: str, plan_id: str, plan_json: str) -> None: ...
    def pinned_plan_json(self, view: View, version: str, plan_id: str) -> tuple[str, str] | None: ...
    def pin_context(self, uow: UnitOfWork, plan_run_id: str, context_json: str) -> None: ...
    def pinned_context(self, view: View, plan_run_id: str) -> tuple[str, str] | None: ...
    def intent_count(self, view: View, plan_run_id: str) -> int: ...
    def next_occurrence(self, view: View, plan_run_id: str, step_id: str) -> int: ...
    def insert_intent(self, uow: UnitOfWork, intent: EscalationIntent) -> None: ...
    def intent(self, view: View, escalation_id: str) -> EscalationIntent | None: ...
    def pending_intents(
        self, view: View, plan_run_id: str, step_id: str | None = None
    ) -> tuple[EscalationIntent, ...]: ...
    def record_intent(self, uow: UnitOfWork, escalation_id: str, help_session_id: str) -> None: ...
    def runs_with_open_escalation(self, view: View, help_session_id: str) -> tuple[PlanRun, ...]: ...
