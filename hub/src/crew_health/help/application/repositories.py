"""Help repositories (E26 4.2): storage of the aggregates, owned by help; never read by another module."""

from __future__ import annotations

from collections.abc import Sequence
from typing import Literal, Protocol

from crew_health.help.domain.broadcast import BroadcastView
from crew_health.help.domain.ground import GroundMessage, HelpLogSnapshot
from crew_health.help.domain.session import HelpSession
from crew_health.kernel.uow import ReadSnapshot, UnitOfWork


class RevisionConflict(Exception):
    """The stored revision moved under the command: nothing was written."""


class OpenSessionExists(Exception):
    """The unique open-subject index refused a second open session for the same person."""


class HelpSessionRepository(Protocol):
    def get(self, uow: ReadSnapshot | UnitOfWork, session_id: str) -> HelpSession | None: ...
    def get_open_for_subject(self, uow: UnitOfWork, person_id: str) -> HelpSession | None: ...
    def insert(self, uow: UnitOfWork, session: HelpSession) -> None: ...
    def save(self, uow: UnitOfWork, session: HelpSession, expected_revision: int) -> None: ...
    def page(
        self,
        uow: ReadSnapshot | UnitOfWork,
        state: Literal["open", "closed"] | None,
        after: str | None,
        limit: int,
    ) -> Sequence[HelpSession]: ...
    def open_sessions(self, uow: ReadSnapshot | UnitOfWork, limit: int) -> Sequence[HelpSession]: ...
    def record_action(
        self, uow: UnitOfWork, session: HelpSession, action: str, actor_ref: str, command_key: str | None
    ) -> None: ...
    def session_for_turn(self, uow: ReadSnapshot | UnitOfWork, help_turn_id: str) -> HelpSession | None: ...
    def save_broadcast(self, uow: UnitOfWork, broadcast: BroadcastView) -> None: ...
    def broadcast_for(self, uow: ReadSnapshot | UnitOfWork, help_session_id: str) -> BroadcastView | None: ...
    def active_broadcasts(self, uow: ReadSnapshot | UnitOfWork, limit: int) -> Sequence[BroadcastView]: ...


class GroundMessageRepository(Protocol):
    def get(self, uow: ReadSnapshot | UnitOfWork, message_id: str) -> GroundMessage | None: ...
    def insert(self, uow: UnitOfWork, message: GroundMessage) -> None: ...
    def save(self, uow: UnitOfWork, message: GroundMessage, expected_revision: int) -> None: ...
    def snapshot(self, uow: ReadSnapshot | UnitOfWork, message_id: str) -> HelpLogSnapshot | None: ...
