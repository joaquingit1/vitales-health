from __future__ import annotations

from collections.abc import Sequence
from typing import Protocol

from crew_health.kernel.commands import CommandIdentity
from crew_health.kernel.uow import SessionContext
from crew_health.knowledge.application import dto
from crew_health.knowledge.application.dto import FormPage as FormPage


class SourceRegistryPort(Protocol):
    def summary(self, source_id: str) -> dto.SourceSummary | dto.SourceUnknown: ...
    def resolve_many(
        self, source_ids: Sequence[str], extra: Sequence[dto.DeclaredSource] = ()
    ) -> dto.ResolutionReport: ...


class ConditionRegistryPort(Protocol):
    def condition_status(
        self, condition_id: str
    ) -> dto.Active | dto.RemovedOrSplit | dto.UnknownCondition: ...
    def active_ids(self) -> frozenset[str]: ...
    def get(self, condition_id: str) -> dto.Condition | None: ...
    def memberships(self, condition_id: str) -> tuple[dto.Membership, ...]: ...
    def aliases(self, condition_id: str) -> tuple[str, ...]: ...
    def counts(self) -> dto.RegistryCounts: ...
    def resolve(self, condition_id: str) -> dto.ConditionResolution | dto.UnknownCondition: ...


class FormTextPort(Protocol):
    def quote_on_page(self, source_id: str, page: int, quote: str) -> bool: ...
    def pages(self, source_id: str) -> Sequence[FormPage] | None: ...


class EvidenceQueryPort(Protocol):
    def active_release(self) -> dto.ActivePointer | dto.NoActiveRelease: ...
    def read_approved(self, release_id: str, passage_id: str, use: dto.AllowedUse) -> dto.ApprovedRead: ...
    def inspect_history(self, passage_id: str, cursor: str | None, limit: int) -> dto.HistoryRead: ...
    def passages_for_sources(
        self,
        release_id: str,
        source_ids: Sequence[str],
        use: dto.AllowedUse,
        filters: dto.ApplicabilityFilter,
        limit: int,
    ) -> dto.SearchResult: ...
    def lexical_search(
        self,
        release_id: str,
        query: str,
        use: dto.AllowedUse,
        filters: dto.ApplicabilityFilter,
        mode: dto.SearchMode,
        k: int,
    ) -> dto.SearchResult: ...
    def dense_search(
        self, release_id: str, query: str, use: dto.AllowedUse, filters: dto.ApplicabilityFilter, k: int
    ) -> dto.SearchResult: ...
    def expand_context(
        self,
        release_id: str,
        passage_id: str,
        use: dto.AllowedUse,
        filters: dto.ApplicabilityFilter,
        neighbors: int,
    ) -> dto.SearchResult: ...
    def pathway_card(self, release_id: str, condition_id: str) -> dto.CardRead: ...
    def discrepancies(self, release_id: str, cursor: str | None, limit: int) -> dto.DiscrepancyPage: ...


class ResearchCatalogPort(Protocol):
    def upsert_item(
        self, session: SessionContext, command: CommandIdentity, request: dto.ItemUpsert
    ) -> dto.CatalogItem: ...
    def register_source(
        self, session: SessionContext, command: CommandIdentity, request: dto.SourceRegistration
    ) -> dto.CatalogItem: ...
    def store_capture(
        self, session: SessionContext, command: CommandIdentity, request: dto.CaptureInput
    ) -> dto.DocumentVersion: ...
    def assess_completeness(
        self, session: SessionContext, command: CommandIdentity, request: dto.CompletenessInput
    ) -> dto.DocumentVersion: ...
    def record_extraction(
        self, session: SessionContext, command: CommandIdentity, request: dto.ExtractionInput
    ) -> dto.Extraction: ...
    def advance_stage(
        self, session: SessionContext, command: CommandIdentity, request: dto.StageInput
    ) -> dto.DocumentVersion: ...
    def set_use_status(
        self, session: SessionContext, command: CommandIdentity, request: dto.UseStatusInput
    ) -> dto.DocumentVersion: ...
    def withdraw_version(
        self, session: SessionContext, command: CommandIdentity, request: dto.WithdrawalInput
    ) -> dto.DocumentVersion: ...
    def record_license(
        self, session: SessionContext, command: CommandIdentity, request: dto.LicenseInput
    ) -> dto.LicenseRecord: ...
    def item(self, item_id: str) -> dto.CatalogItem | None: ...
    def items(self, cursor: str | None, limit: int) -> dto.Page[dto.CatalogItem]: ...
    def versions(self, item_id: str, cursor: str | None, limit: int) -> dto.Page[dto.DocumentVersion]: ...
    def extractions(self, dv_id: str, cursor: str | None, limit: int) -> dto.Page[dto.Extraction]: ...
    def text(self, extraction_id: str, cursor: str | None, limit: int) -> dto.Page[dto.TextBlock]: ...


class ReleaseBuilderPort(Protocol):
    def build(self, review_export: dto.ReviewExport) -> dto.ReleaseBuildResult: ...


class ReleaseAdminPort(Protocol):
    def install(
        self, session: SessionContext, command: CommandIdentity, request: dto.InstallInput
    ) -> dto.ReleaseRecord: ...
    def verify(
        self, session: SessionContext, command: CommandIdentity, request: dto.VerifyInput
    ) -> dto.ReleaseRecord: ...
    def activate(
        self, session: SessionContext, command: CommandIdentity, request: dto.ActivationInput
    ) -> dto.ActivePointer: ...
    def rollback(
        self, session: SessionContext, command: CommandIdentity, request: dto.ActivationInput
    ) -> dto.ActivePointer: ...
    def prune(
        self, session: SessionContext, command: CommandIdentity, request: dto.PruneInput
    ) -> dto.PruneReport: ...
    def list(self, cursor: str | None, limit: int) -> dto.Page[dto.ReleaseRecord]: ...


class ArtifactStore(Protocol):
    """E10-owned public immutable artifact store; publication/backup mechanism is supplied by E01/E20."""

    def put(self, data: bytes) -> dto.ArtifactRef: ...
    def read(self, ref: dto.ArtifactRef) -> bytes: ...


class SignatureVerifier(Protocol):
    def verify(self, key_id: str, payload: bytes, signature: bytes) -> bool: ...
